    def closeEvent(self, event):
        self.settings = Qt.QSettings("gnuradio/flowgraphs", "AviaRadioRecognize1")
        self.settings.setValue("geometry", self.saveGeometry())
        self.stop()
        self.wait()

        event.accept()

